//! Writes the embedded engine into `.state/desktop/` and `.state/proxy/`, the build folders docker compose uses,
//! and keeps them in step with the app.
//!
//! Every embedded file under `desktop/` and `proxy/` is written with a header comment (where the file type allows
//! one). Missing files are written; files that already match are left alone (no write, mtime stays); files that
//! still hold what the app wrote last time (per the manifest) are overwritten silently because the app was updated;
//! files that differ from both were edited by hand, which is restored with a warning. Files in these two folders
//! that the engine no longer has are deleted. Nothing else in `.state/` is touched.
//!
//! The manifest is written last, so a crash halfway is repaired by the next run: every step is idempotent.
//! This module prints nothing: [`sync`] returns what was restored and the caller shows the warnings.

pub mod embedded;
pub mod manifest;

use crate::VERSION;
use crate::paths;
use anyhow::{Context, Result};
use camino::{Utf8Path, Utf8PathBuf};
use manifest::EngineManifest;
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::fs;
use std::sync::LazyLock;

/// The folders below `.state/` that belong to the engine.
const FOLDERS: [&str; 2] = ["desktop", "proxy"];

/// SHA-256 over the sorted names and contents of the embedded `desktop/` and `proxy/` files. Changes exactly when an
/// engine file changes.
pub static ENGINE_HASH: LazyLock<String> = LazyLock::new(compute_engine_hash);

/// What [`sync`] did that is worth telling the user.
#[derive(Debug, Default)]
pub struct SyncReport {
    /// Files (path below `.state/`) that were edited by hand and have been restored.
    pub restored: Vec<String>,
}

/// Lower-case hex.
pub fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write;
    bytes
        .iter()
        .fold(String::with_capacity(bytes.len() * 2), |mut s, b| {
            let _ = write!(s, "{b:02x}");
            s
        })
}

/// The version with the commit shortened to 7 characters, for `info`.
pub fn short_app_version() -> String {
    match VERSION.find('+') {
        Some(plus) if VERSION.len() > plus + 8 => VERSION[..plus + 8].to_string(),
        _ => VERSION.to_string(),
    }
}

/// The first 12 characters of the engine hash, as shown to people.
pub fn short_engine_hash() -> String {
    ENGINE_HASH[..12].to_string()
}

/// The one-line header: `Generated by sandbox 0.1.0 — changes are overwritten. Settings: sandbox.toml.`
pub fn header_text() -> String {
    format!(
        "Generated by sandbox {VERSION} \u{2014} changes are overwritten. Settings: sandbox.toml."
    )
}

/// Brings `.state/desktop` and `.state/proxy` in line with the embedded engine.
pub fn sync(state_dir: &Utf8Path) -> Result<SyncReport> {
    paths::create_dir_all(state_dir)?;
    let manifest_path = state_dir.join(".manifest");
    let old = EngineManifest::read(&manifest_path);
    let expected = expected()?;
    let mut files = BTreeMap::new();
    let mut report = SyncReport::default();

    for (rel, content) in &expected {
        let path = state_dir.join(rel);
        let bytes = content.as_bytes();
        let hash = hash(bytes);
        files.insert(rel.clone(), hash.clone());
        if path.is_file() {
            let current = hash_of_file(&path)?;
            if current == hash {
                continue;
            }
            if old.files.get(rel) != Some(&current) {
                report.restored.push(rel.clone());
            }
        }
        if let Some(parent) = path.parent() {
            paths::create_dir_all(parent)?;
        }
        fs::write(&path, bytes).with_context(|| format!("Could not write {path}"))?;
    }

    for folder in FOLDERS {
        remove_stale(state_dir, folder, &expected)?;
    }

    let manifest = EngineManifest {
        app: VERSION.to_string(),
        engine: ENGINE_HASH.clone(),
        files,
    };
    let json = manifest.to_json();
    if !manifest_path.is_file() || paths::read_text(&manifest_path)? != json {
        paths::write_text(&manifest_path, &json)?;
    }
    Ok(report)
}

/// Every file the engine writes, by path below `.state/` (forward slashes), with its header.
fn expected() -> Result<BTreeMap<String, String>> {
    let mut result = BTreeMap::new();
    for name in engine_names() {
        let text = embedded::read_text(&name)?;
        result.insert(name.clone(), with_header(&name, &text));
    }
    Ok(result)
}

fn engine_names() -> Vec<String> {
    FOLDERS
        .iter()
        .flat_map(|f| embedded::names(&format!("{f}/")))
        .collect()
}

/// Adds the header where the file type has a `#` comment syntax: after the shebang line if there is one, else at
/// the top. Other files (apt and sudoers config, kioslaverc) are left as they are.
pub fn with_header(name: &str, content: &str) -> String {
    let comment = format!("# {}\n", header_text());
    if content.starts_with("#!") {
        return match content.find('\n') {
            None => format!("{content}\n{comment}"),
            Some(eol) => format!("{}{comment}{}", &content[..=eol], &content[eol + 1..]),
        };
    }
    let file = name.rsplit('/').next().unwrap_or(name);
    let has_comments = file == "Dockerfile" || file.ends_with(".conf") || file.ends_with(".sh");
    if has_comments {
        format!("{comment}{content}")
    } else {
        content.to_string()
    }
}

/// Deletes files in `.state/<folder>` that aren't expected, then folders that are empty (deepest first).
fn remove_stale(
    state_dir: &Utf8Path,
    folder: &str,
    expected: &BTreeMap<String, String>,
) -> Result<()> {
    let root = state_dir.join(folder);
    if !root.is_dir() {
        return Ok(());
    }
    let mut files = Vec::new();
    let mut dirs = Vec::new();
    walk(&root, &mut files, &mut dirs)?;
    for file in files {
        let rel = file
            .strip_prefix(state_dir)
            .unwrap_or(&file)
            .as_str()
            .replace('\\', "/");
        if !expected.contains_key(&rel) {
            fs::remove_file(&file).with_context(|| format!("Could not delete {file}"))?;
        }
    }
    dirs.sort_by_key(|d| std::cmp::Reverse(d.as_str().len()));
    for dir in dirs {
        let empty = fs::read_dir(&dir)
            .map(|mut e| e.next().is_none())
            .unwrap_or(false);
        if empty {
            fs::remove_dir(&dir).with_context(|| format!("Could not delete {dir}"))?;
        }
    }
    Ok(())
}

fn walk(dir: &Utf8Path, files: &mut Vec<Utf8PathBuf>, dirs: &mut Vec<Utf8PathBuf>) -> Result<()> {
    for entry in fs::read_dir(dir).with_context(|| format!("Could not read {dir}"))? {
        let entry = entry?;
        let path = paths::to_utf8(entry.path())?;
        if entry.file_type()?.is_dir() {
            dirs.push(path.clone());
            walk(&path, files, dirs)?;
        } else {
            files.push(path);
        }
    }
    Ok(())
}

/// For each name in sorted order: the name's bytes, `0`, the content's bytes, `0`.
fn compute_engine_hash() -> String {
    let mut sha = Sha256::new();
    for name in engine_names() {
        sha.update(name.as_bytes());
        sha.update([0]);
        sha.update(embedded::read_text(&name).unwrap_or_default().as_bytes());
        sha.update([0]);
    }
    hex(&sha.finalize())
}

fn hash(bytes: &[u8]) -> String {
    hex(&Sha256::digest(bytes))
}

fn hash_of_file(path: &Utf8Path) -> Result<String> {
    Ok(hash(
        &fs::read(path).with_context(|| format!("Could not read {path}"))?,
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hex_is_lower_case() {
        assert_eq!(hex(&[0, 15, 255]), "000fff");
    }

    #[test]
    fn header_goes_after_a_shebang_or_on_top_or_nowhere() {
        let h = format!("# {}\n", header_text());
        assert_eq!(
            with_header("desktop/tools/x.sh", "#!/bin/sh\necho\n"),
            format!("#!/bin/sh\n{h}echo\n")
        );
        assert_eq!(with_header("x.sh", "#!/bin/sh"), format!("#!/bin/sh\n{h}"));
        assert_eq!(
            with_header("desktop/Dockerfile", "FROM x\n"),
            format!("{h}FROM x\n")
        );
        assert_eq!(
            with_header("proxy/tinyproxy.conf", "a\n"),
            format!("{h}a\n")
        );
        assert_eq!(
            with_header("desktop/root/etc/xdg/kioslaverc", "[a]\n"),
            "[a]\n"
        );
        assert_eq!(
            with_header("desktop/bin/sandbox-install", "#!/usr/bin/env bash\nx\n"),
            format!("#!/usr/bin/env bash\n{h}x\n")
        );
    }

    #[test]
    fn engine_hash_is_hex_and_covers_only_desktop_and_proxy() {
        assert_eq!(ENGINE_HASH.len(), 64);
        assert!(ENGINE_HASH.chars().all(|c| c.is_ascii_hexdigit()));
        assert!(
            engine_names()
                .iter()
                .all(|n| n.starts_with("desktop/") || n.starts_with("proxy/"))
        );
        assert_eq!(short_engine_hash().len(), 12);
    }

    #[test]
    fn short_version_keeps_seven_commit_characters() {
        let v = short_app_version();
        assert!(v.starts_with("0.1.0"));
        assert!(v.len() <= "0.1.0+".len() + 7);
    }

    #[test]
    fn sync_writes_restores_and_cleans_up() {
        let tmp = tempfile::tempdir().unwrap();
        let state = Utf8Path::from_path(tmp.path()).unwrap().join(".state");
        assert!(sync(&state).unwrap().restored.is_empty());
        let dockerfile = state.join("desktop/Dockerfile");
        let original = fs::read_to_string(&dockerfile).unwrap();
        assert!(original.starts_with("# Generated by sandbox"));

        fs::write(&dockerfile, format!("{original}RUN hacked\n")).unwrap();
        fs::create_dir_all(state.join("desktop/old/deeper")).unwrap();
        fs::write(state.join("desktop/old/deeper/x.sh"), "x").unwrap();
        fs::write(state.join("keep.txt"), "keep").unwrap();
        let report = sync(&state).unwrap();
        assert_eq!(report.restored, vec!["desktop/Dockerfile"]);
        assert_eq!(fs::read_to_string(&dockerfile).unwrap(), original);
        assert!(!state.join("desktop/old").exists());
        assert!(state.join("keep.txt").exists());
        assert!(sync(&state).unwrap().restored.is_empty());

        let m = EngineManifest::read(&state.join(".manifest"));
        assert_eq!(m.engine, *ENGINE_HASH);
        assert_eq!(m.files.len(), engine_names().len());
    }
}
