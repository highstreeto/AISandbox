using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using AiSandbox.Templating;
using AiSandbox.Terminal;

namespace AiSandbox.Project;

/// <summary>
/// Writes the embedded engine into <c>.state/desktop/</c> and <c>.state/proxy/</c>, the build folders docker compose
/// uses, and keeps them in step with the app.
/// </summary>
/// <remarks>
/// <para>
/// Every embedded file under <c>desktop/</c> and <c>proxy/</c> is written with a header comment (where the file type
/// allows one). Missing files are written; files that already match are left alone (no write, mtime stays); files
/// that still hold what the app wrote last time (per the manifest) are overwritten silently because the app was
/// updated; files that differ from both were edited by hand, which is restored with a warning. Files in these two
/// folders that the engine no longer has are deleted. Nothing else in <c>.state/</c> is touched.
/// </para>
/// <para>
/// The manifest is written last, so a crash halfway is repaired by the next run: every step is idempotent.
/// </para>
/// </remarks>
internal static class EngineFiles
{
    /// <summary>
    /// The folders below <c>.state/</c> that belong to the engine.
    /// </summary>
    private static readonly ImmutableArray<string> s_folders = ["desktop", "proxy"];

    private static readonly UTF8Encoding s_utf8 = new(false);

    /// <summary>
    /// <c>AssemblyInformationalVersion</c> (<c>0.1.0+3f2a9c1</c> for builds from git).
    /// </summary>
    public static string AppVersion { get; } =
        typeof(EngineFiles).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion
        ?? "0.0.0";

    /// <summary>
    /// SHA-256 over the sorted names and contents of the embedded <c>desktop/</c> and <c>proxy/</c> files. Changes
    /// exactly when an engine file changes.
    /// </summary>
    public static string EngineHash { get; } = ComputeEngineHash();

    /// <summary>
    /// <see cref="AppVersion"/> with the commit shortened to 7 characters, for <c>info</c>.
    /// </summary>
    public static string ShortAppVersion =>
        AppVersion.IndexOf('+') is var plus and >= 0 && AppVersion.Length > plus + 8
            ? AppVersion[..(plus + 8)]
            : AppVersion;

    /// <summary>
    /// The first 12 characters of <see cref="EngineHash"/>, as shown to people.
    /// </summary>
    public static string ShortEngineHash => EngineHash[..12];

    /// <summary>
    /// The one-line header: <c>Generated by sandbox 0.1.0 — changes are overwritten. Settings: sandbox.toml.</c>
    /// </summary>
    public static string HeaderText =>
        $"Generated by sandbox {AppVersion} \u2014 changes are overwritten. Settings: sandbox.toml.";

    /// <summary>
    /// Brings <c>.state/desktop</c> and <c>.state/proxy</c> in line with the embedded engine.
    /// </summary>
    public static void Sync(string stateDir)
    {
        Directory.CreateDirectory(stateDir);
        var manifestPath = Path.Combine(stateDir, ".manifest");
        var old = EngineManifest.Read(manifestPath);
        var expected = Expected();
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);

        foreach (var (rel, content) in expected)
        {
            var path = Path.Combine(stateDir, rel);
            var bytes = s_utf8.GetBytes(content);
            var hash = Hash(bytes);
            files[rel] = hash;
            if (File.Exists(path))
            {
                var current = Hash(File.ReadAllBytes(path));
                if (current == hash)
                    continue;
                if (!old.Files.TryGetValue(rel, out var written) || written != current)
                    Ui.Warn(
                        $".state/{rel} was edited by hand and has been restored. Generated files are overwritten; change sandbox.toml instead."
                    );
            }
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllBytes(path, bytes);
        }

        foreach (var folder in s_folders)
            RemoveStale(stateDir, folder, expected);

        var manifest = new EngineManifest(
            AppVersion,
            EngineHash,
            files.ToImmutableSortedDictionary(StringComparer.Ordinal)
        );
        var json = manifest.ToJson();
        if (!File.Exists(manifestPath) || File.ReadAllText(manifestPath) != json)
            File.WriteAllText(manifestPath, json, s_utf8);
    }

    /// <summary>
    /// Every file the engine writes, by path below <c>.state/</c> (forward slashes), with its header.
    /// </summary>
    private static SortedDictionary<string, string> Expected()
    {
        var result = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var name in EngineNames())
            result[name] = WithHeader(name, EmbeddedFiles.ReadText(name));
        return result;
    }

    private static ImmutableArray<string> EngineNames() =>
        [.. s_folders.SelectMany(f => EmbeddedFiles.Names(f + "/"))];

    /// <summary>
    /// Adds the header where the file type has a <c>#</c> comment syntax: after the shebang line if there is one,
    /// else at the top. Other files (apt and sudoers config, kioslaverc) are left as they are.
    /// </summary>
    public static string WithHeader(string name, string content)
    {
        var comment = "# " + HeaderText + "\n";
        if (content.StartsWith("#!", StringComparison.Ordinal))
        {
            var eol = content.IndexOf('\n');
            return eol < 0
                ? content + "\n" + comment
                : content[..(eol + 1)] + comment + content[(eol + 1)..];
        }
        var file = name[(name.LastIndexOf('/') + 1)..];
        var hasComments =
            file == "Dockerfile"
            || file.EndsWith(".conf", StringComparison.Ordinal)
            || file.EndsWith(".sh", StringComparison.Ordinal);
        return hasComments ? comment + content : content;
    }

    /// <summary>
    /// Deletes files in <c>.state/&lt;folder&gt;</c> that aren't expected, then folders that are empty.
    /// </summary>
    private static void RemoveStale(
        string stateDir,
        string folder,
        SortedDictionary<string, string> expected
    )
    {
        var root = Path.Combine(stateDir, folder);
        if (!Directory.Exists(root))
            return;
        foreach (var file in Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories))
        {
            var rel = Path.GetRelativePath(stateDir, file).Replace('\\', '/');
            if (!expected.ContainsKey(rel))
                File.Delete(file);
        }
        // Deepest first, so a folder that only held empty folders goes too.
        foreach (
            var dir in Directory
                .EnumerateDirectories(root, "*", SearchOption.AllDirectories)
                .OrderByDescending(d => d.Length)
        )
            if (!Directory.EnumerateFileSystemEntries(dir).Any())
                Directory.Delete(dir);
    }

    private static string ComputeEngineHash()
    {
        using var sha = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        foreach (var name in EngineNames())
        {
            sha.AppendData(s_utf8.GetBytes(name));
            sha.AppendData([0]);
            sha.AppendData(s_utf8.GetBytes(EmbeddedFiles.ReadText(name)));
            sha.AppendData([0]);
        }
        return Convert.ToHexStringLower(sha.GetHashAndReset());
    }

    private static string Hash(byte[] bytes) => Convert.ToHexStringLower(SHA256.HashData(bytes));
}
