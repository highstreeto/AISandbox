using System.Runtime.InteropServices;
using System.Security.Cryptography;
using System.Text;
using YamlDotNet.RepresentationModel;

namespace Sandbox.Tests;

/// The generated compose override (.state/compose.generated.yml) for different settings.
public sealed class ComposeFileTests(SandboxFixture f) : SandboxTest(f)
{
    const string Header = "# Generated by .sandbox/sandbox — do not edit, change sandbox.yml instead.";

    /// Run a cheap docker command so the file is (re)generated, and return its text.
    string Generate()
    {
        var r = Run("status");
        AssertExit(r, 0);
        Assert.True(File.Exists(F.GeneratedFile), $"No generated file.\n{r}");
        return File.ReadAllText(F.GeneratedFile);
    }

    static YamlMappingNode Parse(string text)
    {
        var ys = new YamlStream();
        ys.Load(new StringReader(text));
        return Assert.IsType<YamlMappingNode>(Assert.Single(ys.Documents).RootNode);
    }

    static YamlNode At(YamlNode n, params string[] path)
    {
        foreach (var k in path)
        {
            var m = Assert.IsType<YamlMappingNode>(n);
            Assert.True(m.Children.TryGetValue(new YamlScalarNode(k), out n!), $"missing key '{k}'");
        }
        return n;
    }

    static string Str(YamlNode n, params string[] path) =>
        Assert.IsType<YamlScalarNode>(At(n, path)).Value!;

    static string[] Keys(YamlNode n) =>
        Assert.IsType<YamlMappingNode>(n).Children.Keys.Select(k => ((YamlScalarNode)k).Value!).ToArray();

    record Bind(string Source, string Target, bool ReadOnly);

    static List<Bind> Volumes(YamlNode root) =>
        Assert.IsType<YamlSequenceNode>(At(root, "services", "desktop", "volumes"))
            .Select(v =>
            {
                var m = Assert.IsType<YamlMappingNode>(v);
                Assert.Equal(["type", "source", "target", "read_only"], Keys(m));
                Assert.Equal("bind", Str(m, "type"));
                var ro = Str(m, "read_only");
                Assert.Contains(ro, new[] { "true", "false" });
                return new Bind(Str(m, "source"), Str(m, "target"), ro == "true");
            })
            .ToList();

    Bind Project(bool ro) => new(F.ProjectDir, F.WorkDir, ro);
    Bind SandboxDir => new(F.Dir, F.WorkDir + "/.sandbox", true);
    Bind GitConfig => new(Path.Combine(F.ProjectDir, ".git", "config"), F.WorkDir + "/.git/config", true);
    Bind GitHooks => new(Path.Combine(F.ProjectDir, ".git", "hooks"), F.WorkDir + "/.git/hooks", true);

    [DllImport("libc")]
    static extern uint getuid();

    [DllImport("libc")]
    static extern uint getgid();

    static (uint, uint) ExpectedIds()
    {
        if (OperatingSystem.IsWindows())
            return (1000, 1000);
        var (u, g) = (getuid(), getgid());
        return u == 0 ? (1000, 1000) : (u, g);
    }

    static string Q(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    // --- tests ------------------------------------------------------------------

    [Fact]
    public void Default_file_matches_exactly()
    {
        var (uid, gid) = ExpectedIds();
        string Vol(Bind b) =>
            $"    - {{type: bind, source: {Q(b.Source)}, target: {Q(b.Target)}, read_only: {(b.ReadOnly ? "true" : "false")}}}";
        var expected = string.Join(
            "\n",
            Header,
            "services:",
            "  gateway:",
            "    ports:",
            "    - \"127.0.0.1::3001\"",
            "  desktop:",
            "    labels:",
            $"      sandbox.id: \"{SandboxFixture.Id}\"",
            "    environment:",
            $"      SANDBOX_WORKDIR: \"{F.WorkDir}\"",
            $"      PUID: \"{uid}\"",
            $"      PGID: \"{gid}\"",
            "      TZ: \"Europe/Vienna\"",
            "    volumes:",
            Vol(Project(false)),
            Vol(SandboxDir),
            Vol(GitConfig),
            Vol(GitHooks),
            ""
        );
        var text = Generate();
        Assert.Equal(expected, text);
        Assert.DoesNotContain("\r", text);
        Assert.DoesNotContain("...", text);
        Assert.False(File.ReadAllBytes(F.GeneratedFile).AsSpan().StartsWith(Encoding.UTF8.Preamble), "BOM");
    }

    [Fact]
    public void Default_file_structure()
    {
        var root = Parse(Generate());
        Assert.Equal(["services"], Keys(root));
        Assert.Equal(["gateway", "desktop"], Keys(At(root, "services")));
        Assert.Equal(["ports"], Keys(At(root, "services", "gateway")));
        Assert.Equal(["labels", "environment", "volumes"], Keys(At(root, "services", "desktop")));

        var ports = Assert.IsType<YamlSequenceNode>(At(root, "services", "gateway", "ports"));
        Assert.Equal("127.0.0.1::3001", Assert.IsType<YamlScalarNode>(Assert.Single(ports)).Value);
        Assert.Equal(SandboxFixture.Id, Str(root, "services", "desktop", "labels", "sandbox.id"));
        Assert.Equal(F.WorkDir, Str(root, "services", "desktop", "environment", "SANDBOX_WORKDIR"));
        Assert.Equal("Europe/Vienna", Str(root, "services", "desktop", "environment", "TZ"));
        Assert.Equal([Project(false), SandboxDir, GitConfig, GitHooks], Volumes(root));
    }

    /// The override must only refer to services and ports that exist in engine/compose.yml.
    [Fact]
    public void Override_matches_the_engine_compose_file()
    {
        var gen = Parse(Generate());
        var engine = Parse(File.ReadAllText(Path.Combine(F.Dir, "engine", "compose.yml")));
        var services = Keys(At(engine, "services"));
        Assert.All(Keys(At(gen, "services")), s => Assert.Contains(s, services));

        // gateway publishes the port socat listens on
        var command = Assert.IsType<YamlSequenceNode>(At(engine, "services", "gateway", "command"))
            .Select(n => ((YamlScalarNode)n).Value)
            .ToList();
        Assert.Contains("TCP-LISTEN:3001,fork,reuseaddr", command);
        // desktop keeps its home volume from the engine file; project mounts come from the override
        var engineVolumes = Assert.IsType<YamlSequenceNode>(At(engine, "services", "desktop", "volumes"));
        Assert.Contains("home:/config", engineVolumes.Select(n => (n as YamlScalarNode)?.Value));
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void Fixed_ui_port(bool viaLocal)
    {
        if (viaLocal)
        {
            WriteConf(File.ReadAllText(F.ConfFile).Replace("# ui_port: 3001", "ui_port: 4000"));
            WriteLocalConf("x-sandbox:\n  ui_port: 3002\n");
        }
        else
            WriteConf(File.ReadAllText(F.ConfFile).Replace("# ui_port: 3001", "ui_port: 3002"));
        var root = Parse(Generate());
        var ports = Assert.IsType<YamlSequenceNode>(At(root, "services", "gateway", "ports"));
        Assert.Equal("127.0.0.1:3002:3001", Assert.IsType<YamlScalarNode>(Assert.Single(ports)).Value);
    }

    [Fact]
    public void Read_only_workspace_has_no_git_mounts()
    {
        WriteConf(File.ReadAllText(F.ConfFile).Replace("workspace_mode: rw", "workspace_mode: ro"));
        Assert.Equal([Project(true), SandboxDir], Volumes(Parse(Generate())));
    }

    [Fact]
    public void Local_override_wins_over_sandbox_yml()
    {
        WriteLocalConf("x-sandbox:\n  workspace_mode: ro\n");
        Assert.Equal([Project(true), SandboxDir], Volumes(Parse(Generate())));
    }

    [Fact]
    public void Protect_git_off()
    {
        WriteConf(File.ReadAllText(F.ConfFile).Replace("protect_git: true", "protect_git: false"));
        Assert.Equal([Project(false), SandboxDir], Volumes(Parse(Generate())));
    }

    [Fact]
    public void Only_existing_git_paths_are_protected()
    {
        Directory.Delete(Path.Combine(F.ProjectDir, ".git", "hooks"));
        Assert.Equal([Project(false), SandboxDir, GitConfig], Volumes(Parse(Generate())));

        Directory.Delete(Path.Combine(F.ProjectDir, ".git"), recursive: true);
        Assert.Equal([Project(false), SandboxDir], Volumes(Parse(Generate())));
    }

    [Fact]
    public void Project_name_does_not_change_the_mount_path()
    {
        WriteConf(File.ReadAllText(F.ConfFile).Replace("# project_name: myproject", "project_name: other"));
        var root = Parse(Generate());
        Assert.Equal(F.WorkDir, Str(root, "services", "desktop", "environment", "SANDBOX_WORKDIR"));
    }

    [Fact]
    public void A_new_id_is_derived_from_the_project_path_and_kept()
    {
        File.Delete(F.IdFile);
        var id = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(F.ProjectDir)))[..8];
        var root = Parse(Generate());
        Assert.Equal(id + "\n", File.ReadAllText(F.IdFile));
        Assert.Equal(id, Str(root, "services", "desktop", "labels", "sandbox.id"));
        Assert.Equal(
            $"/work/{SandboxFixture.ProjectName}-{id}",
            Str(root, "services", "desktop", "environment", "SANDBOX_WORKDIR")
        );

        // a stored id is used as-is, even if it doesn't match the path (the project was moved)
        File.WriteAllText(F.IdFile, "cafebabe\n");
        Assert.Equal("cafebabe", Str(Parse(Generate()), "services", "desktop", "labels", "sandbox.id"));
    }

    [Fact]
    public void File_is_regenerated_on_every_docker_command()
    {
        File.WriteAllText(F.GeneratedFile, "stale");
        Assert.StartsWith(Header + "\n", Generate());
        foreach (var cmd in new[] { "stop", "reload", "logs" })
        {
            File.WriteAllText(F.GeneratedFile, "stale");
            AssertExit(Run(cmd), 0);
            Assert.StartsWith(Header + "\n", File.ReadAllText(F.GeneratedFile));
        }
    }
}
