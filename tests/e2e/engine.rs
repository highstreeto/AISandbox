//! The engine the app writes into .state/desktop and .state/proxy before each docker command: files, headers,
//! manifest, hand edits, leftovers, the old .sandbox/engine layout.

use crate::support::*;
use camino::Utf8PathBuf;
use regex::Regex;
use rstest::rstest;
use sha2::{Digest, Sha256};
use std::fs;
use std::time::{Duration, SystemTime};

const EXPECTED_FILES: [&str; 11] = [
    "desktop/Dockerfile",
    "desktop/bin/sandbox-install",
    "desktop/tools/_lib.sh",
    "desktop/tools/node.sh",
    "desktop/tools/claude-code.sh",
    "desktop/root/custom-cont-init.d/50-sandbox",
    "desktop/root/etc/apt/apt.conf.d/95sandbox-proxy",
    "desktop/root/etc/sudoers.d/sandbox-proxy",
    "desktop/root/etc/xdg/kioslaverc",
    "proxy/Dockerfile",
    "proxy/tinyproxy.conf",
];

fn state_path(f: &Fixture, rel: &str) -> Utf8PathBuf {
    f.state_dir().join(rel)
}

fn header(f: &Fixture) -> String {
    format!(
        "# Generated by sandbox {} — changes are overwritten. Settings: sandbox.toml.",
        f.app_version()
    )
}

fn sync(f: &Fixture) -> RunResult {
    let r = f.run(&["status"]);
    assert_exit(&r, 0);
    r
}

/// Every file under .state/desktop and .state/proxy, by path below .state with forward slashes.
fn engine_files_on_disk(f: &Fixture) -> Vec<String> {
    fn walk(dir: &Utf8PathBuf, state: &Utf8PathBuf, out: &mut Vec<String>) {
        let Ok(entries) = fs::read_dir(dir) else {
            return;
        };
        for e in entries {
            let p = Utf8PathBuf::from_path_buf(e.unwrap().path()).unwrap();
            if p.is_dir() {
                walk(&p, state, out);
            } else {
                out.push(p.strip_prefix(state).unwrap().as_str().replace('\\', "/"));
            }
        }
    }
    let mut out = Vec::new();
    for d in [f.desktop_context(), f.proxy_context()] {
        walk(&d, &f.state_dir(), &mut out);
    }
    out.sort_by(|a, b| a.as_bytes().cmp(b.as_bytes()));
    out
}

fn sha(path: &Utf8PathBuf) -> String {
    Sha256::digest(fs::read(path).unwrap())
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

fn manifest(f: &Fixture) -> serde_json::Value {
    serde_json::from_str(&fs::read_to_string(state_path(f, ".manifest")).unwrap()).unwrap()
}

fn first_line(path: &Utf8PathBuf) -> String {
    fs::read_to_string(path)
        .unwrap()
        .lines()
        .next()
        .unwrap_or("")
        .to_string()
}

#[test]
fn the_engine_is_written_on_the_first_command() {
    let f = Fixture::new();
    assert!(!f.desktop_context().exists());
    sync(&f);
    let files = engine_files_on_disk(&f);
    for e in EXPECTED_FILES {
        assert!(files.contains(&e.to_string()), "{e} missing in {files:?}");
    }
    assert!(
        !files
            .iter()
            .any(|x| x.ends_with(".sbn") || x.ends_with(".j2"))
    );
    for x in &files {
        let prefix = if x.starts_with("desktop/") {
            "desktop/"
        } else {
            "proxy/"
        };
        assert!(x.starts_with(prefix), "{x}");
    }
    let tools = Regex::new(r"^desktop/tools/[a-z-]+\.sh$").unwrap();
    let got: Vec<&str> = files
        .iter()
        .filter(|x| tools.is_match(x))
        .map(|x| &x["desktop/".len()..])
        .collect();
    assert_eq!(
        got,
        [
            "tools/apt.sh",
            "tools/bun.sh",
            "tools/claude-code.sh",
            "tools/claude.sh",
            "tools/dotnet.sh",
            "tools/jetbrains.sh",
            "tools/node.sh",
            "tools/rust.sh",
            "tools/vscode.sh"
        ]
    );
}

