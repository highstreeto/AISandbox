#[test]
fn an_old_engine_folder_warns_and_is_kept() {
    let f = Fixture::new();
    let old = f.old_engine_dir();
    fs::create_dir_all(old.join("desktop")).unwrap();
    fs::write(old.join("desktop").join("Dockerfile"), "FROM scratch\n").unwrap();
    let r = sync(&f);
    assert_output(&r, ".sandbox/engine/ is no longer used");
    assert_eq!(
        fs::read_to_string(old.join("desktop").join("Dockerfile")).unwrap(),
        "FROM scratch\n"
    );
    // the app uses its own engine, not the old folder
    assert!(
        fs::read_to_string(state_path(&f, "desktop/Dockerfile"))
            .unwrap()
            .starts_with(&header(&f))
    );
}

