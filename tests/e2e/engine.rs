/// The header comes after a shebang line, never before it.
#[rstest]
#[case("desktop/bin/sandbox-install", "#!/usr/bin/env bash")]
#[case(
    "desktop/root/custom-cont-init.d/50-sandbox",
    "#!/usr/bin/with-contenv bash"
)]
fn the_header_follows_the_shebang(#[case] rel: &str, #[case] shebang: &str) {
    let f = Fixture::new();
    sync(&f);
    let text = fs::read_to_string(state_path(&f, rel)).unwrap();
    let lines: Vec<&str> = text.lines().take(2).collect();
    assert_eq!(lines, [shebang, header(&f).as_str()]);
}

/// A script that has a shebang in the embedded engine still has it on line 1 (the header is never first).
#[test]
fn scripts_with_a_shebang_keep_it_on_the_first_line() {
    let f = Fixture::new();
    sync(&f);
    let header = header(&f);
    for rel in engine_files_on_disk(&f)
        .iter()
        .filter(|x| !x.ends_with("Dockerfile"))
    {
        let text = fs::read_to_string(state_path(&f, rel)).unwrap();
        let lines: Vec<&str> = text.lines().collect();
        if lines.iter().skip(1).any(|l| *l == header) && lines[0].starts_with('#') {
            assert!(lines[0].starts_with("#!"), "{rel}");
        }
        if lines[0] == header {
            assert!(
                ![
                    "desktop/bin/sandbox-install",
                    "desktop/root/custom-cont-init.d/50-sandbox"
                ]
                .contains(&rel.as_str()),
                "{rel}"
            );
        }
    }
}

