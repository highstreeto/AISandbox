using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace AiSandbox.E2ETests;

/// The engine the app writes into .state/desktop and .state/proxy before each docker command: files, headers,
/// manifest, hand edits, leftovers, the old .sandbox/engine layout.
public sealed class EngineTests(SandboxFixture f) : SandboxTest(f)
{
    static readonly string[] ExpectedFiles =
    [
        "desktop/Dockerfile",
        "desktop/bin/sandbox-install",
        "desktop/tools/_lib.sh",
        "desktop/tools/node.sh",
        "desktop/tools/claude-code.sh",
        "desktop/root/custom-cont-init.d/50-sandbox",
        "desktop/root/etc/apt/apt.conf.d/95sandbox-proxy",
        "desktop/root/etc/sudoers.d/sandbox-proxy",
        "desktop/root/etc/xdg/kioslaverc",
        "proxy/Dockerfile",
        "proxy/tinyproxy.conf",
    ];

    string StatePath(string rel) => Path.Combine(F.StateDir, rel);

    string Header => $"# Generated by sandbox {F.AppVersion} — changes are overwritten. Settings: sandbox.toml.";

    RunResult Sync()
    {
        var r = Run("status");
        AssertExit(r, 0);
        return r;
    }

    /// Every file under .state/desktop and .state/proxy, by path below .state with forward slashes.
    IEnumerable<string> EngineFilesOnDisk() =>
        new[] { F.DesktopContext, F.ProxyContext }
            .Where(Directory.Exists)
            .SelectMany(d => Directory.EnumerateFiles(d, "*", SearchOption.AllDirectories))
            .Select(p => Path.GetRelativePath(F.StateDir, p).Replace('\\', '/'))
            .Order(StringComparer.Ordinal);

    static string Sha(string path) => Convert.ToHexStringLower(SHA256.HashData(File.ReadAllBytes(path)));

    JsonElement Manifest() => JsonDocument.Parse(File.ReadAllText(StatePath(".manifest"))).RootElement;

    [Fact]
    public void The_engine_is_written_on_the_first_command()
    {
        Assert.False(Directory.Exists(F.DesktopContext));
        Sync();
        var files = EngineFilesOnDisk().ToList();
        Assert.All(ExpectedFiles, e => Assert.Contains(e, files));
        Assert.DoesNotContain(files, x => x.EndsWith(".sbn", StringComparison.Ordinal));
        Assert.All(files, x => Assert.StartsWith(x.StartsWith("desktop/", StringComparison.Ordinal) ? "desktop/" : "proxy/", x));
        Assert.Equal(
            ["tools/apt.sh", "tools/bun.sh", "tools/claude-code.sh", "tools/claude.sh", "tools/dotnet.sh", "tools/jetbrains.sh", "tools/node.sh", "tools/vscode.sh"],
            files.Where(x => Regex.IsMatch(x, @"^desktop/tools/[a-z-]+\.sh$")).Select(x => x["desktop/".Length..]).ToList()
        );
    }

    [Fact]
    public void The_state_folder_ignores_itself()
    {
        Sync();
        Assert.Equal("*\n", File.ReadAllText(StatePath(".gitignore")));
    }

    [Fact]
    public void Commands_without_docker_do_not_write_the_engine()
    {
        AssertExit(Run("info"), 0);
        Assert.False(Directory.Exists(F.DesktopContext));
    }

    [Fact]
    public void A_second_run_writes_nothing()
    {
        Sync();
        var old = new DateTime(2001, 2, 3, 4, 5, 6, DateTimeKind.Utc);
        var paths = EngineFilesOnDisk().Select(StatePath).Append(StatePath(".manifest")).Append(StatePath(".gitignore")).ToList();
        foreach (var p in paths)
            File.SetLastWriteTimeUtc(p, old);
        var r = Sync();
        Assert.All(paths, p => Assert.Equal(old, File.GetLastWriteTimeUtc(p)));
        Assert.DoesNotContain("WARNING", r.Output);
    }

    [Fact]
    public void A_file_edited_by_hand_is_restored_with_a_warning()
    {
        Sync();
        var path = StatePath("desktop/Dockerfile");
        var original = File.ReadAllText(path);
        File.WriteAllText(path, original + "RUN echo hacked\n");
        var r = Sync();
        AssertOutput(r, ".state/desktop/Dockerfile was edited by hand and has been restored.");
        Assert.Equal(original, File.ReadAllText(path));

        // restored once: no warning the next time
        Assert.DoesNotContain("edited by hand", Sync().Output);
    }

    [Fact]
    public void A_deleted_file_is_written_again_without_a_warning()
    {
        Sync();
        File.Delete(StatePath("proxy/tinyproxy.conf"));
        var r = Sync();
        Assert.True(File.Exists(StatePath("proxy/tinyproxy.conf")));
        Assert.DoesNotContain("WARNING", r.Output);
    }

    /// A file that still holds what an older app version wrote (the manifest says so) is replaced silently.
    [Fact]
    public void A_file_from_an_older_app_version_is_replaced_silently()
    {
        Sync();
        var path = StatePath("desktop/tools/node.sh");
        var original = File.ReadAllText(path);
        File.WriteAllText(path, "#!/bin/sh\n# older engine\n");
        var manifest = File.ReadAllText(StatePath(".manifest"));
        var current = Regex.Match(manifest, "\"desktop/tools/node.sh\": \"([0-9a-f]{64})\"").Groups[1].Value;
        File.WriteAllText(StatePath(".manifest"), manifest.Replace(current, Sha(path)));
        var r = Sync();
        Assert.Equal(original, File.ReadAllText(path));
        Assert.DoesNotContain("WARNING", r.Output);
    }

    [Fact]
    public void Leftover_files_and_empty_folders_are_removed_but_other_state_is_kept()
    {
        Sync();
        Directory.CreateDirectory(StatePath("desktop/old/deeper"));
        File.WriteAllText(StatePath("desktop/old/deeper/x.sh"), "x");
        File.WriteAllText(StatePath("proxy/old.conf"), "x");
        File.WriteAllText(StatePath("built"), "keep\n");
        File.WriteAllText(StatePath("other.txt"), "keep\n");
        Sync();
        Assert.False(Directory.Exists(StatePath("desktop/old")));
        Assert.False(File.Exists(StatePath("proxy/old.conf")));
        Assert.Equal("keep\n", File.ReadAllText(StatePath("built")));
        Assert.Equal("keep\n", File.ReadAllText(StatePath("other.txt")));
        Assert.Equal(SandboxFixture.Id + "\n", File.ReadAllText(F.IdFile));
        Assert.True(File.Exists(F.GeneratedFile));
    }

    [Fact]
    public void The_manifest_has_the_app_version_the_engine_hash_and_the_file_hashes()
    {
        Sync();
        var m = Manifest();
        Assert.Equal(F.AppVersion, m.GetProperty("app").GetString());
        Assert.Matches("^[0-9a-f]{64}$", m.GetProperty("engine").GetString()!);
        var files = m.GetProperty("files");
        Assert.Equal(EngineFilesOnDisk().ToList(), files.EnumerateObject().Select(p => p.Name).ToList());
        foreach (var p in files.EnumerateObject())
            Assert.Equal(Sha(StatePath(p.Name)), p.Value.GetString());
    }

    [Fact]
    public void The_engine_hash_is_stable_and_shown_by_info()
    {
        Sync();
        var hash = Manifest().GetProperty("engine").GetString()!;
        Sync();
        Assert.Equal(hash, Manifest().GetProperty("engine").GetString());
    }

    [Fact]
    public void Dockerfiles_and_scripts_start_with_the_header()
    {
        Sync();
        foreach (var rel in new[] { "desktop/Dockerfile", "proxy/Dockerfile", "proxy/tinyproxy.conf", "desktop/tools/_lib.sh" })
            Assert.Equal(Header, File.ReadLines(StatePath(rel)).First());
        Assert.StartsWith(Header + "\n", File.ReadAllText(F.GeneratedFile));
    }

    /// The header comes after a shebang line, never before it.
    [Theory]
    [InlineData("desktop/bin/sandbox-install", "#!/usr/bin/env bash")]
    [InlineData("desktop/root/custom-cont-init.d/50-sandbox", "#!/usr/bin/with-contenv bash")]
    public void The_header_follows_the_shebang(string rel, string shebang)
    {
        Sync();
        var lines = File.ReadLines(StatePath(rel)).Take(2).ToList();
        Assert.Equal([shebang, Header], lines);
    }

    /// A script that has a shebang in the embedded engine still has it on line 1 (the header is never first).
    [Fact]
    public void Scripts_with_a_shebang_keep_it_on_the_first_line()
    {
        Sync();
        foreach (var rel in EngineFilesOnDisk().Where(x => !x.EndsWith("Dockerfile", StringComparison.Ordinal)))
        {
            var lines = File.ReadAllLines(StatePath(rel));
            if (lines.Skip(1).Any(l => l == Header) && lines[0].StartsWith('#'))
                Assert.StartsWith("#!", lines[0]);
            if (lines[0] == Header)
                Assert.DoesNotContain(rel, new[] { "desktop/bin/sandbox-install", "desktop/root/custom-cont-init.d/50-sandbox" });
        }
    }

    /// Files without a comment syntax get no header.
    [Theory]
    [InlineData("desktop/root/etc/apt/apt.conf.d/95sandbox-proxy")]
    [InlineData("desktop/root/etc/sudoers.d/sandbox-proxy")]
    [InlineData("desktop/root/etc/xdg/kioslaverc")]
    public void Files_without_a_comment_syntax_get_no_header(string rel)
    {
        Sync();
        Assert.DoesNotContain("Generated by sandbox", File.ReadAllText(StatePath(rel)));
    }

    [Fact]
    public void Written_files_use_unix_line_endings()
    {
        Sync();
        Assert.All(EngineFilesOnDisk().Select(StatePath), p => Assert.DoesNotContain('\r', File.ReadAllText(p)));
    }

    [Fact]
    public void The_proxy_config_is_baked_into_the_proxy_image()
    {
        Sync();
        Assert.Contains("COPY --chmod=0644 tinyproxy.conf /etc/tinyproxy/tinyproxy.conf", File.ReadAllText(StatePath("proxy/Dockerfile")));
    }

    [Fact]
    public void The_known_tools_come_from_the_embedded_dockerfile()
    {
        WriteConf("[tools]\nnope = true\n");
        var r = Run("info");
        AssertExit(r, 1);
        AssertOutput(r, "unknown tool tools.nope (known: apt, claude, claude_code, dotnet, node, bun, vscode, jetbrains).");
    }

    [Fact]
    public void An_old_engine_folder_warns_and_is_kept()
    {
        var old = F.OldEngineDir;
        Directory.CreateDirectory(Path.Combine(old, "desktop"));
        File.WriteAllText(Path.Combine(old, "desktop", "Dockerfile"), "FROM scratch\n");
        var r = Sync();
        AssertOutput(r, ".sandbox/engine/ is no longer used");
        Assert.Equal("FROM scratch\n", File.ReadAllText(Path.Combine(old, "desktop", "Dockerfile")));
        // the app uses its own engine, not the old folder
        Assert.StartsWith(Header, File.ReadAllText(StatePath("desktop/Dockerfile")));
    }

    [Fact]
    public void A_sandbox_folder_needs_only_sandbox_toml()
    {
        Assert.False(Directory.Exists(F.OldEngineDir));
        AssertExit(Run("info"), 0);
        Assert.DoesNotContain("engine/ is no longer used", Run("status").Output);
    }

    [Fact]
    public void Info_shows_the_engine_row()
    {
        Sync();
        var r = Run("info");
        AssertExit(r, 0);
        var hash = Manifest().GetProperty("engine").GetString()![..12];
        AssertOutput(r, $"engine {hash}");
        AssertOutput(r, ".sandbox/.state/desktop, proxy (rewritten before each command)");
    }
}
